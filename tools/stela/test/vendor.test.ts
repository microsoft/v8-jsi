import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { StelaError } from "../src/errors.ts";
import { DEFAULT_TEMPLATE } from "../src/stela.ts";
import { generateLibraryHeader, generatedNames, parseTemplate } from "../src/vendor.ts";
import { templateV2 } from "./helpers.ts";

const raw = readFileSync(DEFAULT_TEMPLATE, "utf8");
const template = parseTemplate(raw);
const v8host = () => generateLibraryHeader(template, { macroPrefix: "V8HOST", fileName: "v8host_stela.h" });

test("the template is version 1 with the §5.3 vocabulary", () => {
  assert.equal(template.version, 1);
  assert.deepEqual(template.helpers, ["VERSION", "ANNOTATE_", "FIXED_ENUMS_"]);
  assert.deepEqual(template.vocabulary, [
    "ENUM", "FLAGS", "OUT", "INOUT", "OPTIONAL", "NULLABLE", "TRANSFER_NONE", "TRANSFER_FULL",
    "COUNT", "ZERO_TERMINATED", "ENCODING", "SCOPE_CALL", "SCOPE_ASYNC", "SCOPE_OBJECT",
    "SCOPE_NOTIFIED", "SCOPE_FOREVER", "CLOSURE", "DESTROY", "SINCE", "DEPRECATED",
    "EXPERIMENTAL", "ALLOW", "ATTR",
  ]);
  assert.match(template.sha256, /^[0-9a-f]{64}$/);
});

test("generated file: banner, guard, prefixed names, no #undef", () => {
  const text = v8host();
  const lines = text.split("\n");
  assert.equal(
    lines[0],
    "/* v8host_stela.h: GENERATED by Stela. Do not edit; run `stela vendor` to regenerate.",
  );
  assert.equal(lines[1], " * Prefix: V8HOST. Source: stela.h version 1");
  assert.equal(lines[2], ` * (sha256 ${template.sha256}).`);
  assert.ok(text.includes(" * Licensed under the MIT License. */\n#ifndef V8HOST_STELA_H_\n#define V8HOST_STELA_H_\n\n#define V8HOST_STELA_VERSION 1\n"));
  assert.ok(text.endsWith("\n#endif /* V8HOST_STELA_H_ */\n"));
  assert.doesNotMatch(text, /#undef/);
  assert.doesNotMatch(text, /\r/);
  assert.match(text, /^#define V8HOST_NULLABLE V8HOST_STELA_ANNOTATE_\("nullable"\)$/m);
  assert.match(text, /^#define V8HOST_STELA_ANNOTATE_\(s\) __attribute__\(\(annotate\("stela:" s\)\)\)$/m);
  assert.match(text, /^#if defined\(__clang__\) && defined\(STELA_EXTRACT\)$/m);
  assert.match(text, /^#if V8HOST_STELA_FIXED_ENUMS_$/m);
  assert.match(text, /^  enum V8HOST_STELA_ANNOTATE_\("flags=" #name\) : type$/m);
  // Every STELA_ token except the extractor switch is renamed.
  assert.deepEqual([...new Set(text.match(/\bSTELA_\w*/g))], ["STELA_EXTRACT"]);
  for (const v of template.vocabulary) {
    assert.match(text, new RegExp(`^#define V8HOST_${v}\\b`, "m"), v);
  }
});

test("continuation backslashes line up within each macro", () => {
  const lines = v8host().split("\n");
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].endsWith("\\") || (i > 0 && lines[i - 1].endsWith("\\"))) continue;
    const col = lines[i].length;
    for (let j = i; lines[j].endsWith("\\"); j++) {
      assert.equal(lines[j].length, col, `line ${j + 1}`);
      assert.match(lines[j], /[^ ] +\\$/);
    }
  }
});

test("regeneration is byte-identical and ignores template line endings and BOM", () => {
  assert.equal(v8host(), v8host());
  const crlf = parseTemplate("\uFEFF" + raw.replace(/\r?\n/g, "\r\n"));
  assert.equal(crlf.sha256, template.sha256);
  assert.equal(
    generateLibraryHeader(crlf, { macroPrefix: "V8HOST", fileName: "v8host_stela.h" }),
    v8host(),
  );
});

test("different prefixes share no macro name", () => {
  const macros = (p: string) =>
    new Set([...generateLibraryHeader(template, { macroPrefix: p, fileName: "x_stela.h" })
      .matchAll(/^#define (\w+)/gm)].map((m) => m[1]));
  const sbox = macros("SBOX");
  const jsi = macros("JSI_ABI");
  const v8 = macros("V8HOST");
  for (const name of sbox) assert.ok(!jsi.has(name) && !v8.has(name), name);
  for (const name of jsi) assert.ok(!v8.has(name), name);
  // The helper prefix keeps JSI_ABI's version macro free for jsi_abi.h.
  assert.ok(jsi.has("JSI_ABI_STELA_VERSION"));
  assert.ok(!jsi.has("JSI_ABI_VERSION"));
});

test("stelaNames renames one annotation", () => {
  const text = generateLibraryHeader(template, {
    macroPrefix: "V8HOST",
    fileName: "v8host_stela.h",
    stelaNames: { DEPRECATED: "V8HOST_STELA_DEPRECATED" },
  });
  assert.match(text, /^#define V8HOST_STELA_DEPRECATED V8HOST_STELA_ANNOTATE_\("deprecated"\)$/m);
  assert.doesNotMatch(text, /\bV8HOST_DEPRECATED\b/);
});

test("bad options are rejected", () => {
  const bad = (macroPrefix: string, stelaNames?: Record<string, string>, fileName = "x_stela.h") =>
    assert.throws(() => generateLibraryHeader(template, { macroPrefix, fileName, stelaNames }), StelaError);
  bad("v8host");
  bad("V8HOST_");
  bad("_V8HOST");
  bad("STELA");
  bad("V8HOST", { NOPE: "V8HOST_NOPE" });
  bad("V8HOST", { ENUM: "STELA_ENUM" });
  bad("V8HOST", { ENUM: "not a name" });
  bad("V8HOST", { DEPRECATED: "V8HOST_EXPERIMENTAL" });
  bad("V8HOST", { DEPRECATED: "V8HOST_STELA_VERSION" });
  bad("V8HOST", { DEPRECATED: "V8HOST_STELA_H_" });
  bad("V8HOST", undefined, "../x_stela.h");
  assert.deepEqual(generatedNames(template, "A").get("ANNOTATE_"), "A_STELA_ANNOTATE_");
});

test("malformed templates are rejected", () => {
  const bad = (text: string) => assert.throws(() => parseTemplate(text), StelaError);
  bad("/* no code */\n");
  bad(raw.replace("#if !defined(STELA_VERSION)", "#ifndef STELA_VERSION //"));
  bad(raw.replace("#endif /* STELA_VERSION */", "#endif"));
  bad(raw.replace("#define STELA_VERSION 1", "#define STELA_VERSION 2"));
  bad(raw.replace("/* Lifecycle */", "/* Lifecycle */\n#define STELA_EXTRACT 1"));
  bad(raw.replace("/* Lifecycle */", "/* Lifecycle */\n#define STELA_X STELA_MISSING"));
  bad("#define STRAY 1\n" + raw);
});

test("a v2 template adds a name and bumps the version", () => {
  const v2 = parseTemplate(templateV2(raw));
  assert.equal(v2.version, 2);
  assert.ok(v2.vocabulary.includes("THREAD_ANY"));
  const text = generateLibraryHeader(v2, { macroPrefix: "BETA", fileName: "beta_stela.h" });
  assert.match(text, /^#define BETA_STELA_VERSION 2$/m);
  assert.match(text, /^#define BETA_THREAD_ANY BETA_STELA_ANNOTATE_\("thread=any"\)$/m);
});
