// gen-notice.ts — regenerate the packages' NOTICE.txt files from the vendored
// license set. Run with Node.js v24+ (TypeScript strip-types).
//
// Each NOTICE.txt aggregates every third-party copyright/license notice for the
// components compiled into a package's binaries or shipped as headers:
//   scripts/nuget/NOTICE.txt          Microsoft.JavaScript.V8 (v8jsi.dll,
//                                     v8jsisb.dll, sbox.exe, v8host.dll)
//   scripts/nuget-libnode/NOTICE.txt  Microsoft.JavaScript.LibNode (libnode)
// They are AUTO-GENERATED by scanning deps/ for license files, so they cannot
// silently drift from the vendored set — re-run it after every fork-sync.
//
//   node scripts/gen-notice.ts           # regenerate both NOTICE.txt files
//   node scripts/gen-notice.ts --check   # verify they are current (CI gate); exit 1 on drift
//
// Note: this lists notices for vendored third-party code. The project's own
// license (MIT) ships separately as the package LICENSE, not here.

